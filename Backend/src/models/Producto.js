class Producto {
    constructor(id, nombre, categoria, descripcion, precio, imagen, opciones, destacado, disponible) {
        this.id = id;
        this.nombre = nombre;
        this.categoria = categoria;
        this.descripcion = descripcion;
        this.precio = precio;
        this.imagen = imagen;
        this.opciones = opciones;
        this.destacado = destacado;
        this.disponible = disponible;
    }
}
export default Producto;
