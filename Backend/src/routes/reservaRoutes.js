import { Router } from "express";
import reservaController from "../controllers/ReservaController.js";
import { autenticar } from "../middlewares/autenticar.js";
import { autorizar } from "../middlewares/autorizar.js";
import { Rol } from "../enums/Rol.js";
const router = Router();
const soloCliente = autorizar(Rol.CLIENTE);
const soloPersonal = autorizar(Rol.EMPLEADO, Rol.ADMINISTRADOR);
router.use(autenticar);
router.get("/", soloPersonal, reservaController.getAll);
router.get("/mias", soloCliente, reservaController.getMias);
router.get("/:id", reservaController.getById);
router.post("/", soloCliente, reservaController.create);
router.put("/:id", soloCliente, reservaController.update);
router.patch("/:id/cancelar", reservaController.cancelar);
router.patch("/:id/senia", soloPersonal, reservaController.registrarSenia);
router.patch("/:id/check-in", soloPersonal, reservaController.hacerCheckIn);
router.patch("/:id/finalizar", soloPersonal, reservaController.finalizar);
router.patch("/:id/ausente", soloPersonal, reservaController.marcarAusente);
router.patch("/:id/mesa", soloPersonal, reservaController.asignarMesa);
export default router;
