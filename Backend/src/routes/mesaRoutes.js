import { Router } from "express";
import mesaController from "../controllers/MesaController.js";
import { autenticar } from "../middlewares/autenticar.js";
import { autorizar } from "../middlewares/autorizar.js";
import { Rol } from "../enums/Rol.js";
const router = Router();
const soloAdministrador = autorizar(Rol.ADMINISTRADOR);
router.use(autenticar);
router.get("/", autorizar(Rol.EMPLEADO, Rol.ADMINISTRADOR), mesaController.getAll);
router.get("/:id", soloAdministrador, mesaController.getById);
router.post("/", soloAdministrador, mesaController.create);
router.put("/:id", soloAdministrador, mesaController.update);
router.delete("/:id", soloAdministrador, mesaController.delete);
export default router;
